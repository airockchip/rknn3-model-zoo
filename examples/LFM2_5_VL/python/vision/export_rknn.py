#!/usr/bin/env python
"""Convert posemb vision ONNX -> RKNN and verify with simulator.

Quantization is done here via RKNN built-in 'normal' quantization (default w4a16),
which REQUIRES a calibration dataset (--dataset_path, generated by make_calidata.py).
GRQ (export_vision_posemb.py --quant) is an optional weight-refinement step at the
ONNX stage; it is orthogonal to the bit-width compression done here.

Usage:
    # 3B (default), w4a16 normal quantization
    python export_rknn_posemb.py --modelscope --dataset_path ../quant_data_cn/model_inputs_vision.json

    # 1.6B
    python export_rknn_posemb.py --modelscope --model_size 1.6B --dataset_path ../quant_data_cn/model_inputs_vision.json

    # w8a16
    python export_rknn_posemb.py --quant_dtype w8a16 --dataset_path ../quant_data_cn/model_inputs_vision.json

    # no quantization (fp16)
    python export_rknn_posemb.py --quant_dtype fp16

    # skip simulator verification
    python export_rknn_posemb.py --skip_verify
"""
import os
import sys
import json
import numpy as np
import torch
from rknn.api import RKNN
from PIL import Image

try:
    from transformers import AutoProcessor, AutoModelForImageTextToText
    HAS_TF = True
except ImportError:
    HAS_TF = False

MODEL_CONFIGS = {
    "1.6B": {"model_name": "LiquidAI/LFM2.5-VL-1.6B", "output_basename": "LFM2.5-VL-1.6B"},
    "3B":   {"model_name": "LiquidAI/LFM2.5-VL-3B",   "output_basename": "LFM2.5-VL-3B"},
}


def load_input_shapes(model_dir):
    """Input shapes from vision_config.json (fallback: canonical LFM2.5-VL shapes)."""
    n, flat, rows, dim = 1024, 768, 1024, 1152
    cfg_path = os.path.join(model_dir, 'vision_config.json')
    if os.path.exists(cfg_path):
        with open(cfg_path) as f:
            c = json.load(f)
        n = int(c.get('max_num_patches', n))
        flat = int(c.get('patch_flat', flat))
        rows = int(c.get('pos_emb_rows', rows))
        dim = int(c.get('pos_emb_dim', dim))
        print(f'input shapes from {cfg_path}: n={n} flat={flat} rows={rows} dim={dim}')
    else:
        print(f'[WARN] {cfg_path} not found, using default input shapes')
    return [[1, n, flat], [1, n], [1, rows, dim]]


def convert(args, input_size_list):
    print(f'=== 1. convert {args.onnx} -> {args.output} ===')
    if not os.path.exists(args.onnx):
        print(f'[ERROR] ONNX not found: {args.onnx}')
        return False
    if os.path.exists(args.output) and not args.overwrite:
        print('rknn already exists, skip conversion (use --overwrite to force)')
        return True

    rknn = RKNN(verbose=True)
    if args.quant_dtype in ('w8a16', 'w4a16'):
        # RKNN built-in 'normal' quantization (independent of GRQ done at ONNX stage)
        rknn.config(target_platform=args.target_platform, core_num=args.core_num,
                    quantized_dtype=args.quant_dtype, quantized_algorithm='normal',
                    quantized_method='group32')
        do_quant = True
    else:
        # fp16: format conversion only (GRQ, if any, was already applied at ONNX export)
        rknn.config(target_platform=args.target_platform, core_num=args.core_num)
        do_quant = False
    ret = rknn.load_onnx(model=args.onnx,
                         inputs=['pixel_values', 'pixel_attention_mask', 'pos_emb'],
                         input_size_list=input_size_list)
    assert ret == 0, f'load_onnx failed {ret}'
    ret = rknn.build(do_quantization=do_quant, dataset=None if not do_quant else args.dataset_path)
    assert ret == 0, f'build failed {ret}'
    # save_ctx splits weights into a separate .weight file (required by
    # rknn3_load_model_from_path on device).
    ret = rknn.export_rknn(args.output, save_ctx=True)
    assert ret == 0, f'export failed {ret}'
    rknn.release()
    print('rknn exported:', args.output)
    return True


def verify(args, input_size_list):
    print('=== 2. simulator vs torch ===')
    if not HAS_TF:
        print('transformers unavailable in this env, skip simulator verify')
        return True

    proc = AutoProcessor.from_pretrained(args.model_path, trust_remote_code=True)
    model = AutoModelForImageTextToText.from_pretrained(
        args.model_path, torch_dtype=torch.float32, low_cpu_mem_usage=True,
        trust_remote_code=True).eval()

    if args.verify_image and os.path.exists(args.verify_image):
        img = Image.open(args.verify_image).convert('RGB')
        print(f'verify image: {args.verify_image} ({img.size})')
    else:
        img = Image.new('RGB', (512, 512), color=(128, 128, 128))
        print(f'verify image not found, using 512x512 gray dummy')
    inp = proc(images=img, text='<image>', return_tensors='pt', do_image_splitting=False)
    pv = inp['pixel_values'].float()
    pam = inp['pixel_attention_mask'].float()
    gh, gw = int(inp['spatial_shapes'][0][0]), int(inp['spatial_shapes'][0][1])
    n_patches = input_size_list[0][1]
    grid = int(round(n_patches ** 0.5))
    print(f'img: {img.size}, grid: {gh}x{gw}, mask sum: {int(pam.sum())}')

    with torch.no_grad():
        h = model.model.vision_tower(pixel_values=pv, pixel_attention_mask=pam,
                                     spatial_shapes=inp['spatial_shapes']).last_hidden_state
        h32 = h.reshape(1, grid, grid, -1)
        out_rows = n_patches // 4
        ref = model.model.multi_modal_projector(h32).reshape(1, out_rows, -1)[0]

        vm = model.model.vision_tower
        emb_mod = getattr(vm, 'embeddings', None) or getattr(getattr(vm, 'vision_model', None), 'embeddings', None)
        assert emb_mod is not None, 'cannot find embeddings module'
        pos_w = emb_mod.position_embedding.weight.data
        ps = emb_mod.position_embedding_size
        D = pos_w.shape[1]
        pos2d = pos_w.reshape(ps, ps, D).permute(2, 0, 1).unsqueeze(0).float()
        resized = torch.nn.functional.interpolate(pos2d, size=(gh, gw), mode='bilinear',
                                                  align_corners=False, antialias=True)
        resized = resized.reshape(D, gh * gw).transpose(0, 1)
        if gh * gw < n_patches:
            resized = torch.cat([resized, resized[0:1].expand(n_patches - gh * gw, -1)], dim=0)
        pos_emb = resized.unsqueeze(0).numpy().astype(np.float32)

    pv_np = pv.numpy().astype(np.float32)
    pam_np = pam.numpy().astype(np.float32)

    rknn2 = RKNN(verbose=False)
    if args.quant_dtype in ('w8a16', 'w4a16'):
        rknn2.config(target_platform=args.target_platform, core_num=args.core_num,
                     quantized_dtype=args.quant_dtype, quantized_algorithm='normal',
                     quantized_method='group32')
        do_quant = True
    else:
        rknn2.config(target_platform=args.target_platform, core_num=args.core_num)
        do_quant = False
    ret = rknn2.load_onnx(model=args.onnx,
                          inputs=['pixel_values', 'pixel_attention_mask', 'pos_emb'],
                          input_size_list=input_size_list)
    assert ret == 0, f'load_onnx failed {ret}'
    ret = rknn2.build(do_quantization=do_quant, dataset=None if not do_quant else args.dataset_path)
    assert ret == 0, f'build failed {ret}'
    ret = rknn2.init_runtime()
    assert ret == 0, f'sim init failed {ret}'
    out = rknn2.inference(inputs=[pv_np, pam_np, pos_emb], data_format=['nchw', 'nchw', 'nchw'])[0]
    print('sim out shape:', out.shape)
    sim = out[0] if out.ndim == 3 else out
    sim = sim.astype(np.float32)

    diff = float(np.abs(sim - ref.numpy()).max())
    cos = float(np.dot(sim.flatten(), ref.numpy().flatten()) /
                (np.linalg.norm(sim) * np.linalg.norm(ref.numpy()) + 1e-9))
    print(f'MAXDIFF={diff:.4e}  COS={cos:.8f}')
    rknn2.release()
    if cos < 0.99:
        print('FAIL')
        return False
    print('PASS')
    return True


def main():
    from argparse import ArgumentParser

    parser = ArgumentParser(description="Convert posemb vision ONNX -> RKNN (default w4a16 normal quantization)")
    parser.add_argument('--model_size', type=str, default='1.6B', choices=list(MODEL_CONFIGS.keys()))
    parser.add_argument('--onnx', type=str, default=None,
                        help='input ONNX path (default: ../../model/vision/<basename>-vision-posemb.onnx)')
    parser.add_argument('--output', type=str, default=None,
                        help='output RKNN path (default: ../../model/vision/<basename>-vision-posemb.rknn)')
    parser.add_argument('--target_platform', type=str, default='rk1820')
    parser.add_argument('--core_num', type=int, default=8)
    parser.add_argument('--quant_dtype', type=str, default='w4a16', choices=['w4a16', 'w8a16', 'fp16'],
                        help='RKNN quantization: w4a16 (default) / w8a16 / fp16 (no quant)')
    parser.add_argument('--dataset_path', type=str, default=None,
                        help='calibration dataset index for normal quantization '
                             '(generated by make_calidata.py, e.g. model_inputs.json)')
    parser.add_argument('--model_path', type=str, default=None,
                        help='HF model path/name for simulator verification')
    parser.add_argument('--modelscope', action='store_true', help='download model from ModelScope for verification')
    parser.add_argument('--verify_image', type=str, default='../../data/demo.jpg',
                        help='image for simulator verification (default: ../../data/demo.jpg)')
    parser.add_argument('--skip_verify', action='store_true', help='skip simulator verification')
    parser.add_argument('--overwrite', action='store_true', help='re-convert even if RKNN exists')
    args = parser.parse_args()

    cfg = MODEL_CONFIGS[args.model_size]
    if args.onnx is None:
        args.onnx = f'../../model/vision/{cfg["output_basename"]}-vision.onnx'
    if args.output is None:
        args.output = f'../../model/vision/{cfg["output_basename"]}-vision.rknn'
    if args.model_path is None:
        args.model_path = cfg['model_name']
    if args.modelscope:
        from modelscope import snapshot_download
        args.model_path = snapshot_download(args.model_path)

    input_size_list = load_input_shapes(os.path.dirname(os.path.abspath(args.onnx)))

    if not convert(args, input_size_list):
        sys.exit(1)
    if args.skip_verify:
        print('verification skipped')
        sys.exit(0)
    if not verify(args, input_size_list):
        sys.exit(1)


if __name__ == '__main__':
    main()
