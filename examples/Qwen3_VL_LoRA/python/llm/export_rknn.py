import numpy as np
import os
import sys

# The HF/ONNX matcher is shared with the vision pipeline and lives in python/.
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from rknn.api import RKNN,DEFAULT_RKNN_LLM_CONFIG
from lora_node_map import build_lora_node_map

ONNX_MODEL = './Qwen3-VL-4B-Instruct/Qwen3-VL-4B-Instruct-llm.onnx'
LORA_MODEL = None
LORA_CONFIG = None
LLM_CONFIG = './Qwen3-VL-4B-Instruct/Qwen3-VL-4B-Instruct-llm.config.pkl'
RKNN_MODEL = './Qwen3-VL-4B-Instruct/Qwen3-VL-4B-Instruct-llm.rknn'
DATASET_PATH = None

if __name__ == '__main__':

    from argparse import ArgumentParser
    parser = ArgumentParser(description="Export Qwen/Qwen3-VL llm to RKNN model") 
    parser.add_argument("--onnx_path", type=str, help="onnx model path", required=False, default=ONNX_MODEL)
    parser.add_argument("--lora_path", type=str, help="lora model path", required=False, default=LORA_MODEL)
    parser.add_argument("--lora_config_path", type=str, help="lora config file path", required=False, default=LORA_CONFIG)
    parser.add_argument("--config", type=str, help="config file path", required=False, default=LLM_CONFIG)
    parser.add_argument("--rknn_path", type=str, help="output rknn model path", required=False, default=RKNN_MODEL)
    parser.add_argument("--dataset_path", type=str, help="model quantization dataset path", required=False, default=DATASET_PATH)
    parser.add_argument(
        "--platform",
        type=str,
        help="target platform (rk1820/rk1828/rk3572)",
        required=False,
        default="rk1820",
        choices=["rk1820", "rk1828", "rk3572"],
    )
    parser.add_argument(
        "--hf_onnx_map",
        type=str,
        help="HF weight to ONNX op mapping generated by export_llm.py; defaults to <onnx_path>.hf_onnx_map.json",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--lora_node_map_output",
        type=str,
        help="optional exact RKNN LoRA node map JSON output path",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--lora_node_map_report",
        type=str,
        help="optional LoRA node map report output path",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--lora_filtered_path",
        type=str,
        help="optional output path for LoRA tensors mapped to this LLM ONNX",
        required=False,
        default=None,
    )
    parser.add_argument('--rebuild', action='store_true', required=False, default=False, help='Whether to rebuild the model')
    args = parser.parse_args()

    has_lora_args = args.lora_path is not None or args.lora_config_path is not None
    if args.rebuild and has_lora_args:
        raise ValueError(
            '--rebuild reuses the previous build state and cannot load a new LoRA; '
            'run a full export without --rebuild when changing LoRA inputs'
        )

    # Create RKNN object
    rknn = RKNN(verbose=True)
    if "2b" in args.onnx_path.lower():
        dynamic_input = [[[1, 1],   [1, 1],   [1, 1],   [1, 1, 2048],[1, 1, 2048],[1, 1, 2048], [1]], 
                            [[1, 128], [1, 128], [1, 128], [1, 128, 2048], [1, 128, 2048], [1, 128, 2048], [1]]]
    elif "4b" in args.onnx_path.lower():
        dynamic_input = [[[1, 1],   [1, 1],   [1, 1], [1, 1, 2560], [1, 1, 2560], [1, 1, 2560], [1]], 
                            [[1, 128], [1, 128], [1, 128], [1, 128, 2560], [1, 128, 2560], [1, 128, 2560], [1]]]

    llm_config = DEFAULT_RKNN_LLM_CONFIG.copy()
    llm_config['attention_config'][0]['mrope_type'] = 'Qwen3-VL'
    llm_config['attention_config'][0]['mrope_section'] = [24,20,20]
    llm_config['attention_config'][0]['mrope_new_id_name'] = 'mrope_id_input'
    # 设置最大的长上下文长度
    llm_config['attention_config'][0]['kvcache_buffer_len'] = int(3072)
    # 设置kvcache量化类型，默认是fp16，Int4_to_F16是int4量化
    llm_config['attention_config'][0]['kvcache_dtype'] = "Int4_to_F16"

    # pre-process config
    print('--> config model')
    rknn.config(
        target_platform = args.platform, dynamic_input = dynamic_input,
        quantized_dtype='w4a16', quantized_algorithm='normal', quantized_method='group32',llm_config=llm_config
    )
    print('done')

    if args.rebuild:
        print('--> Rebuilding model')
        ret = rknn.rebuild("./tmp")
        if ret != 0:
            print('Rebuild rknn model failed!')
            exit(ret)
        print('done')
    else:
        # Load model
        print('--> Loading model')
        ret = rknn.load_llm(model=args.onnx_path, config=args.config, seq=[1,128])

        if ret != 0:
            print('Load model failed!')
            exit(ret)

        if has_lora_args:
            if args.lora_path is None or args.lora_config_path is None:
                raise ValueError('--lora_path and --lora_config_path must be provided together')
            if not os.path.isfile(args.lora_path):
                raise FileNotFoundError(f'LoRA safetensors file not found: {args.lora_path}')
            if not os.path.isfile(args.lora_config_path):
                raise FileNotFoundError(f'LoRA config file not found: {args.lora_config_path}')

            onnx_stem = os.path.splitext(args.onnx_path)[0]
            hf_onnx_map_path = args.hf_onnx_map or (onnx_stem + '.hf_onnx_map.json')
            rknn_stem = os.path.splitext(args.rknn_path)[0]
            node_map_output = args.lora_node_map_output or (rknn_stem + '.lora_node_map.json')
            node_map_report = args.lora_node_map_report or (rknn_stem + '.lora_node_map.report.json')
            filtered_lora_path = args.lora_filtered_path or (rknn_stem + '.llm.safetensors')

            print('--> Building exact LoRA node map')
            lora_node_map, lora_load_path, _ = build_lora_node_map(
                lora_path=args.lora_path,
                hf_onnx_map_path=hf_onnx_map_path,
                node_map_output=node_map_output,
                report_output=node_map_report,
                filtered_lora_output=filtered_lora_path,
            )

            ret = rknn.load_lora(
                lora_paths=[[lora_load_path]],
                lora_config_paths=[[args.lora_config_path]],
                lora_patterns=[["lora0_pattern0"]],
                lora_quantized_dtype="int4",
                lora_quantized_method="group32",
                lora_distribute_strategy="less_mem",
                lora_node_map=lora_node_map,
            )

        if ret != 0:
            print('Load model failed!')
            exit(ret)
        print('done')

        # Build model
        print('--> Building model')
        ret = rknn.build(do_quantization=True, dataset=args.dataset_path)
        if ret != 0:
            print('Build model failed!')
            exit(ret)
        print('done')

    # Export rknn model
    print('--> Export rknn model')
    export_rknn_dirname = os.path.dirname(args.rknn_path)
    if export_rknn_dirname and not os.path.exists(export_rknn_dirname):
        os.makedirs(export_rknn_dirname, exist_ok=True)
    ret = rknn.export_rknn(args.rknn_path)
    if ret != 0:
        print('Export rknn model failed!')
        exit(ret)
    print('done')

    rknn.release()
