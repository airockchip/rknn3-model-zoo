import numpy as np
import os,sys
from rknn.api import RKNN
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../../../..')))
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from py_utils.tools import gen_qwen_vl_vision_prune_quantize_dataset
from lora_node_map import build_lora_node_map

ONNX_MODEL = 'Qwen3-VL-2B-vision.onnx'
RKNN_MODEL = 'Qwen3-VL-2B-vision.rknn'
DATASET_PATH = None
LORA_MODEL = None
LORA_CONFIG = None

def load_config(config_path: str):
    import json
    import os
    if not os.path.exists(config_path):
        return 384, 384, np.array([[1,24,24]], dtype=np.int64)

    with open(config_path, 'r', encoding='utf-8') as f:
        config = json.load(f)
    
    required_keys = ['img_h', 'img_w', 'grid_thw']
    for key in required_keys:
        if key not in config:
            raise KeyError(f"Missing key '{key}' in config file")
    return config["img_h"], config["img_w"], np.array([config["grid_thw"]], dtype=np.int64)

img_h, img_w, grid_thw = load_config('vision_config.json')
print(f"Using img_h={img_h}, img_w={img_w}, grid_thw={grid_thw}")

if __name__ == '__main__':

    from argparse import ArgumentParser
    parser = ArgumentParser(description="Qwen/Qwen3-VL vision convert rknn") 
    parser.add_argument("--onnx_path", type=str, help="onnx model path", required=False, default=ONNX_MODEL)
    parser.add_argument("--rknn_path", type=str, help="output rknn model path", required=False, default=RKNN_MODEL)
    parser.add_argument('--platform', type=str, default="rk1820", choices=["rk1820", "rk1828", "rk3572"],
                        help='Target platform (rk1820/rk1828/rk3572)')
    parser.add_argument("--dataset_path", type=str, help="model quantization dataset path", required=False, default=DATASET_PATH)
    parser.add_argument("--lora_path", type=str, help="lora model path", required=False, default=LORA_MODEL)
    parser.add_argument("--lora_config_path", type=str, help="lora config file path", required=False, default=LORA_CONFIG)
    parser.add_argument(
        "--hf_onnx_map",
        type=str,
        help="HF weight to ONNX op mapping generated by export_vision.py; defaults to <onnx_path>.hf_onnx_map.json",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--lora_node_map_output",
        type=str,
        help="optional exact RKNN LoRA node map JSON output path",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--lora_node_map_report",
        type=str,
        help="optional LoRA node map report output path",
        required=False,
        default=None,
    )
    parser.add_argument(
        "--lora_filtered_path",
        type=str,
        help="optional output path for LoRA tensors mapped to this vision ONNX",
        required=False,
        default=None,
    )
    parser.add_argument("--no_prune_mode", dest="prune_mode", action="store_false", help="close prune mode")
    parser.set_defaults(prune_mode=True)
    parser.add_argument(
        "--save_ctx",
        action="store_true",
        default=False,
        help="also export the .ctx context file required by the toolkit simulator / accuracy analysis",
    )
    parser.add_argument('--rebuild', action='store_true', required=False, default=False, help='Whether to rebuild the model')
    args = parser.parse_args()

    has_lora_args = args.lora_path is not None or args.lora_config_path is not None
    if args.rebuild and has_lora_args:
        raise ValueError(
            '--rebuild reuses the previous build state and cannot load a new LoRA; '
            'run a full export without --rebuild when changing LoRA inputs'
        )

    # Create RKNN object
    rknn = RKNN(verbose=True)

    print('--> config model')
    if args.prune_mode == True:
        rknn.config(target_platform=args.platform, core_num=8,
                quantized_dtype='w4a16', quantized_algorithm='normal', quantized_method='group32')
    else:
        rknn.config(target_platform=args.platform, core_num=8,
                    quantized_dtype='w4a16', quantized_algorithm='normal', quantized_method='group32',
                    mean_values=[[0.5 * 255, 0.5 * 255, 0.5 * 255]], #完整版
                    std_values=[[0.5 * 255, 0.5 * 255, 0.5 * 255]],
                    input_attrs={'pixel': {'dtype': 'uint8', 'layout': 'NHWC'}}
                    )
    print('done')

    if args.rebuild:
        print('--> Rebuilding model')
        ret = rknn.rebuild("./tmp")
        if ret != 0:
            print('Rebuild rknn model failed!')
            exit(ret)
        print('done')
    else:
        # Load model
        print('--> Loading model')
        if args.prune_mode == True:
            ret = rknn.load_onnx(model=args.onnx_path,
                             inputs=['/Reshape_1_output_0', 'grid_thw'], #裁剪版
                             input_size_list = [[int(grid_thw[0][1] * grid_thw[0][2]),1536],[1,3]],
                             input_initial_val=[None, grid_thw])
        else:
            ret = rknn.load_onnx(model=args.onnx_path,
                             inputs=['pixel', 'grid_thw'], #完整版
                             input_size_list = [[1,3,img_h,img_w],[1,3]],
                             input_initial_val=[None, grid_thw])
        if ret != 0:
            print('Load model failed!')
            exit(ret)
        print('done')

        if has_lora_args:
            if args.lora_path is None or args.lora_config_path is None:
                raise ValueError('--lora_path and --lora_config_path must be provided together')
            if not os.path.isfile(args.lora_path):
                raise FileNotFoundError(f'LoRA safetensors file not found: {args.lora_path}')
            if not os.path.isfile(args.lora_config_path):
                raise FileNotFoundError(f'LoRA config file not found: {args.lora_config_path}')

            onnx_stem = os.path.splitext(args.onnx_path)[0]
            hf_onnx_map_path = args.hf_onnx_map or (onnx_stem + '.hf_onnx_map.json')
            rknn_stem = os.path.splitext(args.rknn_path)[0]
            node_map_output = args.lora_node_map_output or (rknn_stem + '.lora_node_map.json')
            node_map_report = args.lora_node_map_report or (rknn_stem + '.lora_node_map.report.json')
            filtered_lora_path = args.lora_filtered_path or (rknn_stem + '.vision.safetensors')

            print('--> Building exact vision LoRA node map')
            lora_node_map, lora_load_path, _ = build_lora_node_map(
                lora_path=args.lora_path,
                hf_onnx_map_path=hf_onnx_map_path,
                node_map_output=node_map_output,
                report_output=node_map_report,
                filtered_lora_output=filtered_lora_path,
                scope="vision",
            )

            ret = rknn.load_lora(
                lora_paths=[[lora_load_path]],
                lora_config_paths=[[args.lora_config_path]],
                lora_patterns=[["lora0_pattern0"]],
                lora_quantized_dtype="int4",
                lora_quantized_method="group32",
                lora_distribute_strategy="less_mem",
                lora_node_map=lora_node_map,
            )
            if ret != 0:
                print('Load lora failed!')
                exit(ret)

        if args.prune_mode == True:
            if args.dataset_path is not None:
                ret = gen_qwen_vl_vision_prune_quantize_dataset(args.dataset_path, "../../data/vision/datasets_npy.txt", img_h, img_w, [0.5 * 255, 0.5 * 255, 0.5 * 255], [0.5 * 255, 0.5 * 255, 0.5 * 255], 16)
                if ret == 0:
                    args.dataset_path = "../../data/vision/datasets_npy.txt"
            else:
                args.dataset_path = "../../data/vision/datasets_npy.txt"

        # Build model
        print('--> Building model')
        ret = rknn.build(do_quantization=True, dataset=args.dataset_path)
        if ret != 0:
            print('Build model failed!')
            exit(ret)
        print('done')

    # Export rknn model
    print('--> Export rknn model')
    export_rknn_dirname = os.path.dirname(args.rknn_path)
    if export_rknn_dirname and not os.path.exists(export_rknn_dirname):
        print(f"create export_rknn_dirname: {export_rknn_dirname}")
        os.makedirs(export_rknn_dirname, exist_ok=True)

    ret = rknn.export_rknn(args.rknn_path, save_ctx=args.save_ctx)
    if ret != 0:
        print(f"Export rknn model failed! {args.rknn_path}")
        exit(ret)
    print(f"done {args.rknn_path}")
    
    rknn.release()
